-- Run this in Supabase SQL Editor. Enable email/password auth in Supabase first.
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name_bn text not null unique,
  name_en text not null,
  slug text not null unique,
  created_at timestamptz not null default now()
);
create table if not exists public.articles (
  id uuid primary key default gen_random_uuid(),
  title_bn text not null,
  title_en text,
  slug text not null unique,
  summary_bn text,
  summary_en text,
  body_bn text not null,
  body_en text,
  category_id bigint references public.categories(id),
  cover_image_url text,
  status text not null default 'draft' check (status in ('draft','published')),
  published_at timestamptz,
  author_id uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.categories enable row level security;
alter table public.articles enable row level security;
create policy "categories readable by everyone" on public.categories for select using (true);
create policy "published articles readable by everyone" on public.articles for select using (status = 'published');
